#include <iostream>
using namespace std;
int main() {
    auto a = 10; //  int
    auto b = 20.5; //  double
    auto c = "Hello"; //  const char*
    auto d = 'a'; //  char
    
    cout << "a: " << a << endl;
    cout << "b: " << b << endl;
    cout << "c: " << c << endl;
    cout << "d: " << d << endl;

    return 0;
}